  const dur = await page.evaluate(() => new Promise(r => { const a = document.querySelector('#riListen audio'); if (a.readyState >= 1) return r(a.duration); a.addEventListener('loadedmetadata', () => r(a.duration)); setTimeout(() => r(-1), 3000); }));
  T.ok(dur === Infinity || dur > 0, 'the recording is playable audio (duration ' + dur + ')');
  await page.click('#riFbCard .ri-fix .ri-link');
  T.has(await H.txt(page, '#riFbCard'), 'Hidden.', '"not what I said" hides that mistake locally');
