  T.has(fbTxt, 'not what I said', 'each mistake has "not what I said"');
  T.has(fbTxt, 'A stronger answer', 'a stronger answer');
  T.has(fbTxt, '126 words per minute'.replace('126', String(Math.round(M.TRANSCRIPT_GOOD.split(/\s+/).length / 24 * 60))), 'delivery: wpm');
