  await page.click('.ri-edit:nth-of-type(2) .ri-pk'); await page.click('.ri-edit:nth-of-type(2) .ri-pk');
  await H.sleep(900);
  T.eq(mock.calls.filter(c => c.method === 'PATCH').length - picksBefore, 1, 'rapid ticks collapse into one PATCH');
  await page.click('.ri-edit:nth-of-type(1) .btn');
  await H.sleep(120);
  T.ok((await page.evaluate(() => window.__copied)).some(x => /Built/.test(x)), 'Copy puts the wording on the clipboard');
  T.has(await H.txt(page, '.ri-edit:nth-of-type(1) .btn'), 'Copied', 'and says so');
  T.ok(await H.vis(page, '#riReupload') && await H.vis(page, '#riStart'), 'Re-upload and Start are both offered');

  T.section('step 3 - re-upload an improved resume -> the change is shown');
