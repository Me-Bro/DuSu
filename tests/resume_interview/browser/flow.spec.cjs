  await page.fill('#riResName', '');
  await page.setInputFiles('#riResFile', { name: 'asha-rao-cv.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-FAKE\n' + M.RESUME_TEXT + '\n- Reported weekly KPIs.') });
  await page.waitForSelector('#riPre', { state: 'visible' });
