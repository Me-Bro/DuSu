  await page.click('#riReupload'); await H.waitView(page, 'resume');
  T.has(await H.txt(page, '#riBody'), 'Your improved resume', 'swap mode wording');
  T.has(await H.txt(page, '#riBody'), 'Data Analyst', 'the job stays fixed and visible');
  await page.setInputFiles('#riResFile', { name: 'v2.txt', mimeType: 'text/plain', buffer: Buffer.from(M.RESUME_IMPROVED) });
  await page.waitForSelector('#riPre', { state: 'visible' });
  await page.click('#riLooks');
  await page.waitForSelector('#riPrev', { state: 'visible', timeout: 15000 });
  const swap = mock.calls.find(c => c.path.endsWith('/swap-resume'));
  T.ok(swap && swap.body.resume_id === mock.docs.filter(d => d.kind === 'resume').pop().id, 'POST /swap-resume with the new resume id');
  T.has(await H.txt(page, '#riPrev'), 'Compared with your previous resume', 'the comparison card');
  const bandAfter = await H.txt(page, '#riHero .score-ring .val small');
  T.ok(bandBefore !== bandAfter, `the band moved (${bandBefore} -> ${bandAfter})`);
  T.has(await H.txt(page, '#riPrev'), `${bandBefore} → ${bandAfter}`.replace(/\s+/g, ' ').trim() === '' ? '' : '→', 'before -> after is shown');
  T.has(await H.txt(page, '#riPrev'), 'Power BI dashboards', 'the requirement that changed is named');
  T.ok(await page.evaluate(() => !!document.querySelector('.ri-edit.done')), 'an edit is marked as done in the new resume');
  T.has(await H.txt(page, '.ri-edit.done'), 'Done in your new resume', 'with a text label');

  T.section('step 4 - start the interview');
  mock.sttQueue = [];
  await H.startInterview(page);
  T.eq(await url(), '/resume-interview/interview', 'interview URL');
  T.has(await H.txt(page, '#riQ'), 'Question 1', 'question number');
  T.has(await H.txt(page, '#riQ'), 'Power BI dashboard you built', 'the question text');
  T.has(await H.txt(page, '#riQ'), 'Why this question:', '"Why this question" is shown');
  const fin0 = await page.evaluate(() => ({ t: document.getElementById('riFin').textContent, d: document.getElementById('riFin').disabled }));
  T.ok(fin0.d && /Finish interview — 3 more to unlock/.test(fin0.t), 'Finish is locked: "' + fin0.t + '"');
  T.eq(await H.txt(page, '#riCnt'), '', 'no counter while Finish is locked (its label already says how many are missing)');
  T.ok(await H.vis(page, '#riSkip'), 'Skip is offered on an open question');
  T.ok(!(await H.vis(page, '#riNextQ')), 'Next is not offered before an answer');

  T.section('the question is read aloud; the mic is off while she speaks and the voice is cancelled before the mic opens');
  await page.waitForFunction(() => !document.getElementById('riMic').disabled, null, { timeout: 8000 });   // the question was read aloud when it appeared: let that finish
  await page.evaluate(() => { window.__ttsMs = 1800; });
  await page.click('#riHear');
  await H.sleep(200);
  T.ok(await page.evaluate(() => document.getElementById('riMic').disabled), 'the mic button is DISABLED while DuSu speaks');
  T.has(await H.txt(page, '#riStage'), 'DuSu is asking', 'and says why');
  await page.evaluate(() => { window.__events.length = 0; });
  await page.waitForFunction(() => !document.getElementById('riMic').disabled, null, { timeout: 8000 });
  T.ok(true, 'the mic comes back when she has finished');
  await page.click('#riMic');
  await page.waitForSelector('#riRec');
  const e1 = await ev();
  T.ok(e1.indexOf('cancel') >= 0 && e1.indexOf('gum') > e1.indexOf('cancel'), 'speechSynthesis.cancel() ran BEFORE getUserMedia: ' + JSON.stringify(e1));
  await page.evaluate(() => { window.__ttsMs = 80; });

  T.section('recording: timer, level meter, wrap-up');
  T.ok(await H.vis(page, '#riTimer'), 'a timer');
  T.has(await H.txt(page, '#riRec'), 'of 3:00', 'the limit is shown');
  await H.sleep(700);
  const tm = await H.txt(page, '#riTimer');
  T.ok(/^0:0[1-9]$/.test(tm), 'the timer runs: ' + tm);
  T.ok(!(await page.evaluate(() => !!document.getElementById('riMic'))), 'no mic button while recording: the dock shows Stop');
  T.ok(await H.vis(page, '#riStop'), 'the Stop button is in the dock');
  T.eq(await page.evaluate(() => document.getElementById('riRecHint').getAttribute('aria-live')), 'polite', 'the guidance line is aria-live');
  await H.sleep(500);
  await page.click('#riStop');
  await page.waitForSelector('#riFbCard', { state: 'visible', timeout: 20000 });

  T.section('answer 1 -> transcription (the learner\'s own Groq key, from the phone) -> feedback');
  T.eq(env.groq.calls.length, 1, 'one Groq call');
  const gq = env.groq.calls[0];
  T.eq(gq.headers.authorization, 'Bearer gsk_test_key_123', 'Groq called with the learner\'s own key');
  T.eq(gq.fields.model[0], 'whisper-large-v3-turbo', 'model');
  T.eq(gq.fields.response_format[0], 'verbose_json', 'response_format');
  T.eq(gq.fields['timestamp_granularities[]'], ['word', 'segment'], 'word + segment timestamps');
  T.eq(gq.fields.temperature[0], '0', 'temperature 0');
  T.eq(gq.fields.language[0], 'en', 'English forced');
  T.ok(gq.fields.prompt[0].length <= 200 && /Role: Data Analyst/.test(gq.fields.prompt[0]) && /Terms: .*(SQL|BI)/.test(gq.fields.prompt[0]), 'the prompt is <= 200 chars with the role and skills: ' + gq.fields.prompt[0]);
  T.ok(gq.fileLen > 500, 'the recording itself was uploaded');
  const ans = mock.answers[0].body;
  T.eq(ans.engine, 'groq', 'engine groq');
  T.ok(Array.isArray(ans.words) && ans.words.length > 10 && ans.words[0].length === 3 && typeof ans.words[0][1] === 'number', 'words mapped to [w, s, e]');
  T.ok(Array.isArray(ans.segments) && ans.segments[0].length === 4, 'segments mapped to [s, e, avg_logprob, no_speech_prob]');
  T.ok(ans.duration_sec > 0, 'duration_sec sent');
  T.ok(ans.client_key && ans.audio_device && /^d/.test(ans.audio_device), 'client_key and audio_device sent');
  T.eq(ans.transcript, M.TRANSCRIPT_GOOD, 'the transcript is what Whisper returned');
  const fbTxt = await H.txt(page, '#riFbCard');
  T.has(fbTxt, 'Content: Good', 'band chip: Content');
  T.has(fbTxt, 'Language: Needs work', 'band chip: Language');
  T.has(fbTxt, 'Delivery: Good', 'band chip: Delivery');
  T.ok(!/\b(62|52|55|74|70)\b/.test(await H.txt(page, '#riBands')), 'NO raw numbers per answer in the bands');
  T.has(fbTxt, 'What DuSu heard (from the transcript)', 'what DuSu heard');
  T.has(await H.txt(page, '#riHeard'), 'I make dashboard', 'the transcript text');
  T.has(fbTxt, 'What worked', 'what worked');
  T.has(fbTxt, 'I make dashboard', 'mistake quote');
