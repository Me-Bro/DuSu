  T.eq(await H.view(page), 'match', 'now on the match view');
  const sessCall = mock.calls.find(c => c.method === 'POST' && c.path === '/rinterview/sessions');
  T.eq(sessCall.body.settings, { type: 'technical', level: 'experienced', feedback_lang: 'en' }, 'session settings from the chips');
  T.ok(sessCall.body.client_key, 'POST /sessions carries a client_key');
  T.eq(mock.calls.filter(c => c.path.endsWith('/analyze')).length, 1, 'exactly one analyze call');
  T.ok(mock.calls.find(c => c.path.endsWith('/analyze')).body.keys !== undefined, 'analyze carries "keys": officeKeys()');

  T.section('step 3 - match');
  const hero = await H.txt(page, '#riHero');
  T.has(hero, 'Data Analyst', 'role title in the hero');
  T.ok(/\d/.test(await H.txt(page, '#riHero .score-ring .val b')), 'a score in the ring');
  T.has(hero, "Match score — DuSu's estimate", 'the score is labelled an estimate');
  const reqs = await page.evaluate(() => [...document.querySelectorAll('.ri-req')].map(r => ({ cls: r.className, txt: r.textContent })));
  T.ok(reqs.length === 5, 'five requirement cards');
  T.ok(reqs.every(r => /Missing|Partly there|Matched/.test(r.txt)), 'every requirement carries a TEXT status label');
  T.ok(reqs.some(r => /✕/.test(r.txt)) && reqs.some(r => /✓/.test(r.txt)), 'and a glyph');
  T.ok(await page.evaluate(() => !!document.querySelector('.ri-det.missing[open]')), 'the Missing group is open');
  T.has(await H.txt(page, '.ri-det.met summary'), 'Matched (', 'the Matched group has a count');
  const nEdits = await page.evaluate(() => document.querySelectorAll('.ri-edit').length);
  T.ok(nEdits >= 2, 'suggested edits are listed');
  T.ok((await H.txt(page, '.ri-edit')).includes('Only if true for you'), 'edits that add a claim carry "Only if true for you"');
  await page.click('.ri-edit:nth-of-type(1) .ri-pk');
