  T.has(decodeURIComponent(up.headers['x-ri-name']), 'Resume · ', 'default display title');
  T.ok(up.rawLen > 100, 'the file is the raw body');
  T.has(await H.txt(page, '#riPre'), 'Reported weekly KPIs', 'the kept text from the upload is shown');

  T.section('step 2 - the job');
  await page.click('#riLooks'); await H.waitView(page, 'job');
  T.eq(await url(), '/resume-interview/job', 'job URL');
  T.has(await H.txt(page, '#riBody'), 'Resume', 'the chosen resume is shown on the job step');
  await page.fill('#riJdText', 'short');
  await page.click('#riNext');
  await H.waitNote(page);
  T.has(await H.noteText(page), 'too short', 'a too-short JD is refused before any call');
  await page.fill('#riJobTitle', 'Data Analyst');
  await page.fill('#riJobCompany', 'Acme Corp');
  await page.fill('#riJdText', M.JD_TEXT);
  await page.click('#riType .ri-chip:nth-of-type(3)');
  await page.click('#riLevel .ri-chip:nth-of-type(2)');
  await page.click('#riFbLang .ri-chip:nth-of-type(2)');
  T.eq(await page.evaluate(() => document.querySelector('#riType .on').dataset.v), 'technical', 'type chip selected');
