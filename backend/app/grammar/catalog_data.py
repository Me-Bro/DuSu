"""Bilingual lesson content per grammar rule (Appendix B of the approved Grammar Coach plan).

CONTENT[rule_id] = {
    "en": {title, rule, pattern, why_slip, tip},            plain English
    "hi": {title, rule, pattern, why_slip, tip},            Hinglish: Hindi in ROMAN letters, tum / aap / no pronoun, never tu / tera / tujhe,
                                                            no gendered verb endings aimed at the learner
    "good":  [3 correct, natural spoken sentences]          shared by both languages
    "pairs": [3 {"wrong", "right"}]                         realistic spoken slips and a minimal fix
    "drills": [5 {"q", "options"(3), "answer"(index), "explain_en", "explain_hi"}]
    "reviewed": False                                       the owner / a native reviewer flips it
}
FLOW_TIPS[flow_id] = {"en", "hi", "band"}                   fixed, kind, never shaming

Everything here is fixed, reviewed text: no model writes any of it. The tests (tests/grammar/unit_catalog.py) lint every limit below.
Drill answers rotate deterministically (the correct option is placed at (rule number + drill number) % 3) so the answer is not always "first".
"""

from __future__ import annotations

_Q = "Which sentence is correct?"

CONTENT: dict = {}


def _add(rid, en, hi, good, pairs, drills, q=_Q):
    """en = (title, rule, pattern, why_slip, tip); hi = (title, rule, why_slip, tip); pairs = [(wrong, right)] x3;
    drills = [(correct, wrong1, wrong2, explain_en, explain_hi)] x5."""
    base = len(CONTENT)
    items = []
    for k, (ok, w1, w2, ex_en, ex_hi) in enumerate(drills):
        pos = (base + k) % 3
        opts = [w1, w2]
        opts.insert(pos, ok)
        items.append({"q": q, "options": opts, "answer": pos, "explain_en": ex_en, "explain_hi": ex_hi})
    t, r, p, w, tip = en
    ht, hr, hw, htip = hi
    CONTENT[rid] = {
        "en": {"title": t, "rule": r, "pattern": p, "why_slip": w, "tip": tip},
        "hi": {"title": ht, "rule": hr, "pattern": p, "why_slip": hw, "tip": htip},
        "good": list(good),
        "pairs": [{"wrong": a, "right": b} for a, b in pairs],
        "drills": items,
        "reviewed": False,
    }


